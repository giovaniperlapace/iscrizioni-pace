export function phonePrefixValue(selection: string): string {
  return selection.split(":")[0];
}

// Existing saved drafts store only the calling code; retain that representation.
export function phonePrefixSelection(selection: string): string {
  if (selection === OTHER_PHONE_PREFIX || selection.includes(":")) return selection;
  const legacyCountries: Record<string, string> = {
    "+1": "US", "+39": "IT", "+44": "GB", "+47": "NO", "+61": "AU", "+358": "FI",
  };
  const option = PHONE_PREFIX_OPTIONS.find(option =>
    option.value === selection && (!legacyCountries[selection] || option.country === legacyCountries[selection])
  );
  return option ? `${option.value}:${option.country}` : selection;
}

export function localizedPhonePrefixes(locale: SupportedLocale) {
  const names = new Intl.DisplayNames([locale], { type: "region" });
  return PHONE_PREFIX_OPTIONS.map(option => ({
    ...option,
    selection: `${option.value}:${option.country}`,
    label: `${names.of(option.country)} ${option.value}`,
  })).sort((a, b) => a.label.localeCompare(b.label, locale));
}
